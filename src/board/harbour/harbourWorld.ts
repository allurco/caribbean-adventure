import { createWrap, type MapWrap } from "../../game/hex";
import { getMapPreset } from "../../game/mapConfig";
import type { MapCell } from "../../game/types";
import type { GeneratedMap } from "../../game/mapRequest";
import { createMapWorkerRunner } from "../../mapWorker/createMapWorkerRunner";
import { generateMapOffThread } from "../../mapWorker/generateMapOffThread";
import { HARBOUR_MAP, harbourTarget, type Vec3 } from "./harbourView";

/** The harbour scene's world (the still's capture, #122): its map, the seed every seeded visual draws from (ADR 0007), and where the camera looks. */
export interface HarbourWorld {
  cells: MapCell[];
  wrap: MapWrap;
  seed: number;
  target: Vec3;
}

/** The harbour's world, the same on every load (#122): the fixed map, generated by `generateMap`, and its harbour. */
export async function buildHarbourWorld(generateMap: () => Promise<GeneratedMap>): Promise<HarbourWorld> {
  const map = await generateMap();
  return {
    cells: map.cells,
    wrap: createWrap(getMapPreset(map.mapSize).columns),
    seed: map.mapSeed,
    target: harbourTarget(map.cells),
  };
}

let pending: Promise<HarbourWorld> | null = null;

/** The harbour's world, its map generated in the map worker (#124), built once per page and shared. */
export function harbourWorldOnce(): Promise<HarbourWorld> {
  pending ??= buildHarbourWorld(() => generateMapOffThread(HARBOUR_MAP, createMapWorkerRunner()));
  return pending;
}
